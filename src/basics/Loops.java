public class Loops {
    public static void main(String[] args) {

        // For loop
        System.out.println("For Loop:");
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

        // While loop
        System.out.println("While Loop:");
        int j = 1;
        while (j <= 5) {
            System.out.println(j);
            j++;
        }
    }
}
